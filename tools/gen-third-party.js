// Generates THIRD_PARTY_NOTICES.md: every package shipped inside the DeskPTT
// binary (production dependencies + Electron), with its license text.
// Usage: npm run notices

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const root = path.join(__dirname, '..');
const LICENSE_FILES = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i;

// Paths of all production packages, as installed.
const out = execSync('npm ls --omit=dev --all --parseable', { cwd: root, encoding: 'utf8' });
const dirs = [...new Set(out.split(/\r?\n/).map((l) => l.trim()).filter(Boolean))]
  .filter((d) => path.resolve(d) !== path.resolve(root));

function readPkg(dir) {
  try { return JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')); } catch { return null; }
}

function licenseTexts(dir) {
  let files = [];
  try { files = fs.readdirSync(dir).filter((f) => LICENSE_FILES.test(f)); } catch {}
  return files.map((f) => ({ file: f, text: fs.readFileSync(path.join(dir, f), 'utf8').trim() }));
}

function repoUrl(pkg) {
  const r = pkg.repository;
  const url = typeof r === 'string' ? r : r && r.url;
  if (!url) return pkg.homepage || '';
  return url
    .replace(/^git\+/, '')
    .replace(/\.git$/, '')
    .replace(/^github:/, 'https://github.com/')
    .replace(/^git@github\.com:/, 'https://github.com/')
    .replace(/^git:\/\//, 'https://')
    .replace(/^([\w.-]+\/[\w.-]+)$/, 'https://github.com/$1'); // forme courte « owner/repo »
}

const entries = [];
const seen = new Set();
for (const dir of dirs) {
  const pkg = readPkg(dir);
  if (!pkg || seen.has(`${pkg.name}@${pkg.version}`)) continue;
  seen.add(`${pkg.name}@${pkg.version}`);
  entries.push({ name: pkg.name, version: pkg.version, license: pkg.license || 'see text', url: repoUrl(pkg), texts: licenseTexts(dir) });
}

// Electron is a devDependency for npm, but its runtime is shipped in the binary.
const electron = readPkg(path.join(root, 'node_modules', 'electron'));
if (electron) {
  entries.push({
    name: 'electron', version: electron.version, license: electron.license, url: 'https://github.com/electron/electron',
    texts: licenseTexts(path.join(root, 'node_modules', 'electron')),
    extra: 'Electron embeds Chromium and Node.js. Their licenses are shipped with the application in LICENSES.chromium.html and LICENSE.electron.txt.',
  });
}
entries.sort((a, b) => a.name.localeCompare(b.name));

let md = `# Third-party notices

DeskPTT is licensed under the Apache License 2.0 (see LICENSE). The DeskPTT
binary includes the following third-party software. This file is generated by
\`npm run notices\` (tools/gen-third-party.js) — do not edit it by hand.

## libuiohook (inside uiohook-napi) — LGPL-3.0-or-later

uiohook-napi statically includes libuiohook, Copyright (C) 2006-2023
Alexander Barker, licensed under the GNU Lesser General Public License,
version 3 or (at your option) any later version.

- Source: https://github.com/kwhat/libuiohook (and https://github.com/SnosMe/uiohook-napi for the binding)
- License texts: https://www.gnu.org/licenses/lgpl-3.0.html and https://www.gnu.org/licenses/gpl-3.0.html
- You may replace \`resources\\app.asar.unpacked\\node_modules\\uiohook-napi\\prebuilds\\win32-x64\\uiohook-napi.node\`
  in the installation folder with your own build of the library.

## Summary

| Package | Version | License | Source |
|---|---|---|---|
${entries.map((e) => `| ${e.name} | ${e.version} | ${e.license} | ${e.url} |`).join('\n')}

## License texts
`;

for (const e of entries) {
  md += `\n### ${e.name} ${e.version} — ${e.license}\n\n`;
  if (e.url) md += `Source: ${e.url}\n\n`;
  if (e.extra) md += `${e.extra}\n\n`;
  if (!e.texts.length) md += `_No license file in the package; license declared in package.json: ${e.license}._\n`;
  for (const t of e.texts) md += `<details><summary>${t.file}</summary>\n\n\`\`\`text\n${t.text}\n\`\`\`\n\n</details>\n`;
}

fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), md);
console.log(`THIRD_PARTY_NOTICES.md: ${entries.length} packages`);
